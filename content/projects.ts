/** Проект попадает в фильтр по основной категории или по дополнительной. */
export function matchesFilter(project: ProjectItem, filter: string): boolean {
  if (filter === "Все") return true;
  return project.category === filter || (project.alsoIn?.includes(filter) ?? false);
}
