/**
 * Русская микротипографика.
 *
 * ТЗ просит убрать висячие предлоги («ИИ и автоматизация — в закрытом
 * контуре»). Вместо того чтобы расставлять &nbsp; руками по строкам и потом
 * терять их при каждой правке текста, правило описано один раз здесь и
 * применяется к заголовкам и лидам.
 *
 * Что делает:
 *   • привязывает короткие слова (предлоги, союзы, частицы до 2 букв)
 *     к следующему слову;
 *   • не даёт тире уехать в начало строки — привязывает его к предыдущему;
 *   • не даёт числу оторваться от единицы измерения.
 */

const NBSP = " ";

/**
 * Короткие слова, которые не должны висеть в конце строки.
 *
 * Разделитель перед словом взят просмотром назад, а не в группу: иначе
 * регулярка съедает его вместе с совпадением, и второе короткое слово подряд
 * («ИИ и автоматизация») остаётся необработанным.
 */
const SHORT_WORD = /(?<=^|[\s(«"])([a-zA-Zа-яёА-ЯЁ]{1,2})\s+/g;

/** Тире с пробелом перед ним — пробел делаем неразрывным. */
const DASH = /\s+([—–])\s/g;

/** Число и следующее за ним слово. */
const NUMBER_UNIT = /(\d)\s+([а-яёa-z])/gi;

export function typo(text: string): string {
  return text
    .replace(SHORT_WORD, (_m, word: string) => `${word}${NBSP}`)
    .replace(DASH, `${NBSP}$1 `)
    .replace(NUMBER_UNIT, `$1${NBSP}$2`);
}
