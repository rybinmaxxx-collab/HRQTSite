/**
 * Главная.
 *
 * Страница похудела с одиннадцати разделов до восьми, и это была её главная
 * проблема: «пока скролил — заебался, надо чёт убирать». Убрано три раздела и
 * сокращены четыре оставшихся.
 *
 * Что ушло и куда:
 *   • цитата основателя — снята совсем (см. комментарий в sections.tsx);
 *   • «Работаем с вашим ландшафтом» — на /about: это объяснение метода, а не
 *     аргумент для первого знакомства, и оно дублировало соседний блок про
 *     закрытый контур;
 *   • «Прозрачный процесс» — туда же: пять шагов работы читают, когда уже
 *     выбирают подрядчика, а не когда смотрят, чем компания занимается;
 *   • разбор восемнадцати проектов — на /projects, где его листают, а не
 *     раскрывают кликами.
 *
 * Что сжалось: услуг шесть вместо восьми, проектов две карточки вместо
 * четырёх с фильтрами, пакеты — три колонки вместо карусели с вкладками,
 * команда — без развернутой простыни и без счётчиков.
 *
 * Порядок прежний, по воронке: чем занимаемся → кто мы → с кем говорим → как
 * защищаем данные → чем докажем → что спросят → сколько стоит и заявка.
 * Пакеты стоят последними намеренно: раздел стал закрывающим CTA страницы,
 * поэтому отдельной секции с призывом за ним больше нет.
 *
 * Общая обёртка появления у разделов не используется: секция внутри неё
 * всегда оказывается первым ребёнком, срабатывает first:pt-0, и верхний
 * отступ пропадает у всех разделов сразу. Каждый раздел анимирует себя
 * изнутри.
 *
 * Герой намеренно почти без движения: он виден сразу, а анимировать первый
 * экран — значит задержать то, ради чего пришли.
 */
export default function Home() {
  return (
    <>
      <div className="brand-glow">
        <Hero />
        <Marquee />
      </div>

      <Services />
      <Team />
      <Audiences />
      <Security />
      <Projects />
      <Faq />
      <Packages />
      <Footer cta={false} />
    </>
  );
}
